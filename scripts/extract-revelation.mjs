#!/usr/bin/env node
// Extract Revelation (계시록) from 개역한글.txt and emit a typed TS module.
// Source format: `계{chapter}:{verse} {text}` per line.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const SOURCE = join(ROOT, '개역한글.txt');
const OUTPUT = join(ROOT, 'src', 'infrastructure', 'data', 'revelation.ts');

const raw = readFileSync(SOURCE, 'utf8');
const lines = raw.split(/\r?\n/);

const lineRe = /^계(\d+):(\d+)\s+(.+)$/;
const byChapter = new Map();

for (const line of lines) {
  const m = lineRe.exec(line);
  if (!m) continue;
  const chapter = Number(m[1]);
  const verse = Number(m[2]);
  const text = m[3].trim();
  if (!byChapter.has(chapter)) byChapter.set(chapter, []);
  byChapter.get(chapter).push({ verseNumber: verse, text });
}

const chapters = [...byChapter.entries()]
  .sort((a, b) => a[0] - b[0])
  .map(([chapter, verses]) => ({
    chapterNumber: chapter,
    verses: verses.sort((a, b) => a.verseNumber - b.verseNumber),
  }));

if (chapters.length === 0) {
  console.error('No Revelation verses found. Check source file.');
  process.exit(1);
}

const verseTotal = chapters.reduce((s, c) => s + c.verses.length, 0);
const charTotal = chapters.reduce(
  (s, c) => s + c.verses.reduce((ss, v) => ss + [...v.text].length, 0),
  0,
);

const body = `// AUTO-GENERATED by scripts/extract-revelation.mjs — do not edit by hand.
// Source: 개역한글.txt (계시록)
// Chapters: ${chapters.length}, Verses: ${verseTotal}, Chars: ${charTotal}

import type { Chapter } from '@domain/scripture/Chapter';

export const revelation: readonly Chapter[] = ${JSON.stringify(chapters, null, 2)};
`;

mkdirSync(dirname(OUTPUT), { recursive: true });
writeFileSync(OUTPUT, body, 'utf8');

console.log(`Extracted ${chapters.length} chapters, ${verseTotal} verses, ${charTotal} chars.`);
console.log(`Wrote ${OUTPUT}`);
